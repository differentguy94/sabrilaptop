AC_G = [((18.4, 27.1), (20.7, 27.1), "ستارة هوائية 2.0 م فوق المدخل الرئيسي"), ((21.6, 35.45), (23.5, 35.45), "ستارة هوائية 1.8 م فوق شباك التوصيل")]
def sym_ik(s, x, y): s.dot(x, y, 0.1); s.circle(x, y, 0.22); s.text(x + 0.25, y + 0.2, "IK", h=0.09)
def sym_ac(s, x, y): s.pline([(x - 0.35, y), (x + 0.35, y)], width=0.1); s.text(x, y - 0.12, "AIR CURTAIN", h=0.07, attach=2)
LEGEND = [
    (sym_ik, "صاعق حشرات كهربائي UV 30W - تثبيت جداري ارتفاع 2.0 م", "UV electric insect killer 30W wall mounted h 2.0 m"),
    (sym_ac, "ستارة هوائية فوق الفتحات الخارجية (سرعة 10 م/ث)", "air curtain over external openings"),
]
def legend(s, x, y): return s.legend(x, y, "جدول رموز الناموسية - INSECT CONTROL LEGEND", LEGEND, w=10.5, rh=0.5)
def draw_G(s):
    for i, (x, y, loc) in enumerate(IK_G, 1):
        s.device_dot(x, y, 0.35, letter=f"IK{i}")
    for (p1, p2, lab) in AC_G:
        s.pline([p1, p2], width=0.12)
        s.leader([((p1[0] + p2[0]) / 2, p1[1]), ((p1[0] + p2[0]) / 2 + 1.5, p1[1] - 1.1 if p1[1] < 30 else p1[1] - 1.4)])
        s.text((p1[0] + p2[0]) / 2 + 1.5, (p1[1] - 1.15) if p1[1] < 30 else p1[1] - 1.45, lab, attach=1, **C)
        s.dim(p1, p2, offset=0.35 if p1[1] < 30 else -0.3, **D)
    s.leader([(17.9, 27.6), (16.0, 25.95)]); s.text(16.0, 25.9, "صاعق حشرات 30W داخل المدخل\\Pارتفاع 2.0 م بعيداً عن الطعام", attach=3, **C)
    s.leader([(15.6, 37.0), (13.6, 38.3)]); s.text(13.6, 38.4, "صاعق حشرات على جدار المطبخ\\Pليس فوق مناطق تحضير الطعام", attach=2, **C)
    s.dim((15.6, 37.0), (24.0, 37.0), offset=-0.6, **D); s.dim((22.5, 35.7), (26.0, 35.4), offset=-0.9, **D); s.dim((26.0, 35.4), (28.6, 37.2), offset=0.5, horizontal=False, **D)
    s.dim((7.4, 27.6), (17.9, 27.6), offset=0.9, **D)
    s.text(12.5, 29.6, f"العدد: صاعق حشرات {len(IK_G)} + ستارة هوائية {len(AC_G)} في الطابق الأرضي", h=0.14, attach=5, color=7)
    x0, y0, x1, y1 = EMPTY_G
    legend(s, x0 + 0.2, y1 - 0.1)
    s.notes(34.8, 45.0, ["صاعقات الحشرات UV 30W بغطاء لاصق (لا كهربائي) داخل المطبخ وفق اشتراطات البلدية", "تثبيت جداري ارتفاع 2.0 م وعلى بعد 2 م على الأقل من أسطح تحضير الطعام",
                         "ستارة هوائية فوق المدخل الرئيسي 2.0 م وشباك التوصيل 1.8 م مع مفتاح باب", "استبدال أنابيب UV كل 12 شهراً", "شبك ناموسية على جميع فتحات التهوية الخارجية"],
            h=0.14, w=9.0, title="ملاحظات مكافحة الحشرات")
