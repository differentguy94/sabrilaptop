LAYER = "E-INSECT"
D = dict(color=1, h=0.12); C = dict(h=0.12, color=7)
IK_G = [(17.9, 27.6, "داخل المدخل - يسار الباب"), (22.5, 35.7, "شباك التوصيل"), (15.6, 37.0, "المطبخ - الجدار الغربي"), (24.0, 37.0, "المطبخ - جدار التحضير"), (26.0, 35.4, "ممر الخدمة"), (28.6, 37.2, "أسفل الدرج")]
