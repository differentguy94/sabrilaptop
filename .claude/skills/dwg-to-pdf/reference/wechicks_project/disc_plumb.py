def _seglen(pts): return sum(((b[0]-a[0])**2+(b[1]-a[1])**2)**0.5 for a, b in zip(pts, pts[1:]))
def _pipe(s, pts, color, lw, lt, label, w=0.0):
    s.pline(pts, color=color, lw=lw, linetype=lt, width=w)
    mx, my = pts[len(pts)//2]; s.text(mx + 0.12, my + 0.12, f"{label} L={_seglen(pts):.1f}م", h=0.1, color=color)
    return _seglen(pts)
